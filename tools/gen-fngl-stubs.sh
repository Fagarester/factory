#!/bin/sh
# Writes fnsdl/fngl_stubs.h: 1024 stubs for GL functions the driver lacks (each logs its number once, fngl.c).
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/fnsdl/fngl_stubs.h"
N=1024
{
  echo "// Generated by hand-run script: $N missing-function stubs."
  i=0; while [ $i -lt $N ]; do echo "static uint64_t stub_$i(void) { return stub_hit($i); }"; i=$((i + 1)); done
  echo "static uint64_t (*const stubs[])(void) = {"
  i=0; while [ $i -lt $N ]; do echo "  stub_$i,"; i=$((i + 1)); done
  echo "};"
} > "$OUT"
